// ── 変換処理 ────────────────────────────────────────

console.log(`変換開始: ${lines.length} 路線`);

const output = lines.map(line => {
  const prefId = line.prefecture?.id ?? 13;
  const region = REGION_MAP[prefId] ?? 'その他';

  // カラー決定: 個別 > 事業者プレフィックス > デフォルト
  const opPrefix = Math.floor(line.id / 1000);
  const color = LINE_COLORS[line.id]
    ?? OPERATOR_COLORS[opPrefix]
    ?? '#888888';

  const stations = line.stations.map((st, idx) => ({
    id: `g${st.id}`,
    name: st.name.ja,
    nameKana: st.name.ja,  // kanaデータなし、jaで代替
    lineId: `g${line.id}`,
    order: idx,
    lat: st.location.lat,
    lng: st.location.lng,
  }));

  return {
    id: `g${line.id}`,
    name: line.name.ja,
    nameKana: line.name.ja,
    color,
    region,
    lat: line.lat,
    lng: line.lng,
    stations,
  };
});

// ── TypeScript ファイル生成 ──────────────────────────

const ts = `// AUTO-GENERATED by scripts/generate-gtfs-data.mjs — DO NOT EDIT
// Source: japan-train-data npm package (784 lines, 16321 stations)
// Generated: ${new Date().toISOString()}

export interface GtfsStation {
  id: string;
  name: string;
  nameKana: string;
  lineId: string;
  order: number;
  lat: number;
  lng: number;
}

export interface GtfsLine {
  id: string;
  name: string;
  nameKana: string;
  color: string;
  region: string;
  lat: number;
  lng: number;
  stations: GtfsStation[];
}

export const GTFS_LINES: GtfsLine[] = ${JSON.stringify(output, null, 2)};
`;

writeFileSync('src/data/gtfsData.ts', ts, 'utf8');

const totalStations = output.reduce((s, l) => s + l.stations.length, 0);
